import { chmod, mkdir, readFile, writeFile, copyFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const androidRoot = path.resolve(scriptDirectory, "..");
const destinationDirectory = path.join(androidRoot, "android/app/src/main/assets");
const glueSource = require.resolve("svgbob-wasm/svgbob_wasm_bg.js");
const wasmSource = require.resolve("svgbob-wasm/svgbob_wasm_bg.wasm");
const htmlSource = path.join(androidRoot, "assets/ascii-diagram-renderer.html");
const webModuleDestination = path.join(androidRoot, "src/rendering/svgbob-wasm.generated.ts");

const glue = await readFile(glueSource, "utf8");
const wasmBase64 = (await readFile(wasmSource)).toString("base64");
const withoutImport = glue.replace(
  "import * as wasm from './svgbob_wasm_bg.wasm';",
  `let wasm;
let wasmPromise;
async function initializeSvgbob() {
  if (wasm !== undefined) return;
  wasmPromise ??= WebAssembly.instantiate(
    Uint8Array.from(atob(${JSON.stringify(wasmBase64)}), (character) => character.charCodeAt(0)),
    {},
  ).then(({ instance }) => { wasm = instance.exports; });
  await wasmPromise;
}`,
);
if (withoutImport === glue) throw new Error("Svgbob WASM import was not found");
const browserGlue = withoutImport.replace(
  "export function render(ascii) {",
  "window.renderSvgbob = async function render(ascii) {\n    await initializeSvgbob();",
);
if (browserGlue === withoutImport) throw new Error("Svgbob render export was not found");

await mkdir(destinationDirectory, { recursive: true });
const javascriptDestination = path.join(destinationDirectory, "svgbob-wasm.js");
const htmlDestination = path.join(destinationDirectory, "ascii-diagram-renderer.html");
await Promise.all([
  writeFile(javascriptDestination, browserGlue, "utf8"),
  writeFile(webModuleDestination, `/* Generated by scripts/sync-ascii-diagram-asset.mjs. */\nexport const svgbobWasmBase64: string = ${JSON.stringify(wasmBase64)};\n`, "utf8"),
  copyFile(htmlSource, htmlDestination),
]);
await Promise.all([chmod(javascriptDestination, 0o644), chmod(webModuleDestination, 0o644), chmod(htmlDestination, 0o644)]);
