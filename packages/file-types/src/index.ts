const MARKDOWN_EXTENSIONS = new Set(["md", "markdown"]);
const HTML_EXTENSIONS = new Set(["htm", "html", "xhtml"]);
const IMAGE_EXTENSIONS = new Set(["avif", "bmp", "gif", "heic", "heif", "jpeg", "jpg", "png", "webp"]);
const AUDIO_EXTENSIONS = new Set(["aac", "flac", "m4a", "mp3", "ogg", "opus", "wav", "webm"]);

/** Filename-only classification used before bytes or MIME metadata exist.
 * The registry is generated from the same Pierre language table as the full
 * code editor and intentionally does not guess from file contents. */
export function isKnownCodeOrTextFile(value: string): boolean {
  const basename = fileBasename(value);
  return CODE_FILE_IDENTIFIERS.has(basename) || CODE_FILE_IDENTIFIERS.has(fileExtension(basename));
}

export function isMarkdownFile(value: string): boolean {
  return MARKDOWN_EXTENSIONS.has(fileExtension(value));
}

export function isHtmlFile(value: string): boolean {
  return HTML_EXTENSIONS.has(fileExtension(value));
}

export function fileMediaKind(value: string, mimeType = ""): "image" | "audio" | null {
  const mime = mimeType.split(";", 1)[0]?.trim().toLowerCase() ?? "";
  if (mime.startsWith("image/")) return "image";
  if (mime.startsWith("audio/")) return "audio";
  const extension = fileExtension(value);
  if (IMAGE_EXTENSIONS.has(extension)) return "image";
  if (AUDIO_EXTENSIONS.has(extension)) return "audio";
  return null;
}

export function fileExtension(value: string): string {
  const basename = fileBasename(value);
  const boundary = basename.lastIndexOf(".");
  return boundary < 0 ? "" : basename.slice(boundary + 1);
}

export function fileBasename(value: string): string {
  const clean = value.split(/[?#]/u, 1)[0] ?? "";
  return clean.split("/").filter(Boolean).at(-1)?.toLowerCase() ?? "";
}
